pub fn is_modifier(kind: &str) -> bool {
    let class = kind.split(['.', '<']).next().unwrap_or(kind);
    matches!(
        class,
        "Align"
            | "AnimatedAlign"
            | "AnimatedContainer"
            | "AnimatedOpacity"
            | "AnimatedPadding"
            | "AspectRatio"
            | "BackdropFilter"
            | "Baseline"
            | "Card"
            | "Center"
            | "ClipOval"
            | "ClipPath"
            | "ClipRRect"
            | "ClipRect"
            | "ColorFiltered"
            | "ConstrainedBox"
            | "Container"
            | "DecoratedBox"
            | "Expanded"
            | "Flexible"
            | "FittedBox"
            | "FractionallySizedBox"
            | "GestureDetector"
            | "IgnorePointer"
            | "Listener"
            | "MouseRegion"
            | "Offstage"
            | "Opacity"
            | "OverflowBox"
            | "Padding"
            | "Positioned"
            | "PreferredSize"
            | "RepaintBoundary"
            | "RotatedBox"
            | "SafeArea"
            | "Semantics"
            | "ShaderMask"
            | "SizedBox"
            | "Transform"
            | "UnconstrainedBox"
            | "Visibility"
    )
}
